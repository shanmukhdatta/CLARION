def git_tracked(root: Path) -> list[str]:
    files = subprocess.check_output(["git", "-C", str(root), "ls-files"], text=True)
    return sorted(x for x in files.splitlines() if x)

def role(path: str) -> tuple[str, str, str, str]:
    if path in CONTRACTS:
        return CONTRACTS[path]
    if path.startswith("frontend/src/features/"):
        leaf = path.rsplit("/", 1)[-1]
        topic, needed = FEATURES.get(leaf, (leaf, "local evidence"))
        return (
            "Typed localhost API responses", f"Plan the {topic.lower()} component layer",
            f"specialized React presentation for {needed}", "Leaf TSX files are architectural placeholders until implemented and tested"
        )
    return (
        "Approved, versioned parent-folder inputs",
        f"Organize the {path.rsplit('/', 1)[-1].replace('_',' ')} subsystem",
        "documented child outputs",
        "Check actual per-file implementation and acceptance status; directory names are not feature guarantees",
    )

def file_status(path: Path) -> str:
    if path.suffix in (".py", ".ts", ".tsx", ".sh", ".css", ".yml", ".yaml", ".toml", ".json"):
        body = path.read_text(encoding="utf-8", errors="replace")[:1600]
        if any(x in body for x in ("FILE BLUEPRINT ONLY", "TODO: implementation", "DESIGN BLUEPRINT ONLY", "FILE BLUEPRINT", "NOT FUNCTIONAL")):
            return "Blueprint stub"
        if path.stat().st_size < 600 and path.suffix in (".py", ".ts", ".tsx"):
            if path.name == "__init__.py":
                return "Package marker"
            if "placeholder" in body.lower() or "to be implemented" in body.lower() or "Phase:" in body:
                return "Blueprint stub"
        if "schema" in path.parts or path.parent.name == "models" and path.suffix == ".yaml":
            return "Design/config (check parser wiring)"
        return "Executable source / config (validate)"
    if path.suffix == ".md":
        return "Specification or guide"
    return "Source asset / fixture"

def description(path: Path) -> str:
    ext = path.suffix.lower()
    if ext == ".md":
        try:
            for line in path.read_text(encoding="utf-8", errors="replace").splitlines()[:20]:
                if line.startswith("# "):
                    return line[2:].strip()[:108]
        except OSError:
            pass
    if ext in (".py", ".tsx", ".ts") and path.exists():
        content = path.read_text(encoding="utf-8", errors="replace")[:1000]
        match = re.search(r'^[ \t]*(?:"{3}|\'{3})(.*?)(?:"{3}|\'{3})', content, flags=re.S)
        if match:
            return re.sub(r"\s+", " ", match.group(1).strip())[:105]
    return {
        ".yml":"CI or configuration specification", ".yaml":"Versioned settings",
        ".json":"Typed data or metadata", ".md":"Markdown reference",
        ".css":"Local styles", ".tsx":"React component", ".py":"Python module",
        ".ts":"TypeScript contract", ".sh":"Shell entrypoint",
    }.get(ext, "Versioned resource")

