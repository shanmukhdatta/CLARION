def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="rewrite tracked README guide markers")
    parser.add_argument("--check", action="store_true", help="fail if generated guides differ")
    args = parser.parse_args()
    if args.write == args.check:
        parser.error("specify exactly one of --write or --check")
    root = Path(__file__).resolve().parents[2]
    tracked = git_tracked(root)
    dirs: set[str] = set()
    names: dict[str, list[str]] = defaultdict(list)
    childdirs: dict[str, set[str]] = defaultdict(set)
    for entry in tracked:
        pieces = Path(entry).parts
        parent = str(Path(entry).parent)
        if parent != ".":
            names[parent].append(pieces[-1])
        for k in range(1, len(pieces)):
            directory = "/".join(pieces[:k])
            dirs.add(directory)
            if k > 1:
                childdirs["/".join(pieces[:k-1])].add(pieces[k-1])
    changed = []
    for rel in sorted(dirs):
        path = root / rel / "README.md"
        prior = path.read_text(encoding="utf-8") if path.is_file() else f"# `{rel}/` — CLARION folder guide\n"
        if START in prior:
            if END not in prior:
                raise ValueError(f"unclosed marker in {path}")
            prior = prior[:prior.index(START)].rstrip() + "\n\n"
        else:
            prior = prior.rstrip() + "\n\n"
        content = prior + generate_for(root, rel, {k: sorted(v) for k,v in childdirs.items()}, names)
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            changed.append(str(path.relative_to(root)))
            if args.write:
                path.write_text(content, encoding="utf-8")
    index_path = root / "docs/FOLDER_README_INDEX.md"
    groups: dict[str, list[str]] = defaultdict(list)
    for rel in sorted(dirs):
        groups[rel.split("/")[0]].append(rel)
    lines = [
        "# CLARION — Every-folder technical README index",
        "",
        f"**Coverage:** {len(dirs)} tracked folders; each should contain `README.md`.",
        "Generated deterministically from Git-tracked file paths. This is a navigation index, **not proof of feature completion**.",
        "",
        "## Contents", "",
    ]
    lines.extend(f"- [{group}](#{group.replace('.', '').replace('_','-')})" for group in sorted(groups))
    lines.append("")
    for group, paths in sorted(groups.items()):
        lines.extend([f"## {group}", ""])
        for rel in paths:
            _, purpose, _, _ = role(rel)
            lines.append(f"- [`{rel}/README.md`](../{quote(rel, safe='/._-')}/README.md) — {purpose}.")
        lines.append("")
    index = "\n".join(lines).rstrip() + "\n"
    if not index_path.exists() or index_path.read_text(encoding="utf-8") != index:
        changed.append("docs/FOLDER_README_INDEX.md")
        if args.write:
            index_path.write_text(index, encoding="utf-8")
    root_readme = root / "README.md"
    current = root_readme.read_text(encoding="utf-8")
    link_start = "<!-- CLARION_FOLDER_INDEX_LINK -->"
    link_end = "<!-- /CLARION_FOLDER_INDEX_LINK -->"
    if link_start in current:
        if link_end not in current:
            raise ValueError("unclosed top-level index link")
        current = current[:current.index(link_start)].rstrip() + "\n\n"
    else:
        current = current.rstrip() + "\n\n"
    addition = (
        f"{link_start}\n## Folder-by-folder technical architecture and implementation audit\n\n"
        f"Browse [all {len(dirs)} folder READMEs](docs/FOLDER_README_INDEX.md) for a file index, diagrams, "
        f"interfaces, technologies and status. [Feature coverage audit](docs/architecture/FEATURE_IMPLEMENTATION_AUDIT.md) "
        f"separates tested synthetic paths, partial methods and missing real-world evidence.\n{link_end}\n"
    )
    root_expected = current + addition
    if root_readme.read_text(encoding="utf-8") != root_expected:
        changed.append("README.md")
        if args.write:
            root_readme.write_text(root_expected, encoding="utf-8")
    print(f"tracked_directories={len(dirs)} changed={len(changed)} mode={'WRITE' if args.write else 'CHECK'}")
    if args.check and changed:
        print("Outdated README files:", *changed[:30], sep="\n  ", file=sys.stderr)
        return 1
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
